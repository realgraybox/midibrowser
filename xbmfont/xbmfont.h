/* xbmfont.h - embedded bitmap fonts for Xlib programs, single header.
 *
 * Draws text with fonts compiled into the program, so it looks the same on
 * every X server - no server font path, no "fixed" that differs between
 * machines - and scales by whole numbers for large screens. Plain Xlib, C99.
 *
 * Use:
 *     #define XBMFONT_IMPLEMENTATION      // in exactly one .c file
 *     #include "xbmfont.h"
 *     #include "fonts/xbf_fixed_6x13.h"   // the fonts you want
 *
 *     xbf_ctx *t = xbf_create(dpy, window, &xbf_fixed_6x13, 2);
 *     xbf_draw(t, window, 10, 30, 0xFFFFFF, "Hello, æøå!");
 *     xbf_free(t);
 *
 * Text is UTF-8. Code points the font has are drawn; others, and control
 * characters, are drawn as '?'. The bundled fonts have ASCII, Latin-1, Latin
 * Extended-A, the curly quotes, dashes, euro etc. of Windows-1252, arrows and a
 * few symbols. A byte that is not valid UTF-8 is taken as Windows-1252 (Latin-1
 * plus quotes and dashes in 0x80-0x9F), so old 8-bit file names and MIDI
 * texts still show right.
 * Coordinates are like XDrawString: x is the left edge, y the baseline.
 *
 * How it works: xbf_create() uploads all glyphs of one font at one scale to
 * the X server once, as a 1-bit pixmap. Each character is then drawn as a
 * stippled rectangle from that pixmap: two small requests, nothing to wait for.
 * A context belongs to one Display; a program with two connections (e.g. a
 * file dialog with its own) makes one context per connection.
 *
 * Define XBMFONT_STATIC before the include to make the functions static.
 *
 * zlib License - Copyright (c) 2026 M.Glargaard aka realgraybox (see LICENSE)
 */
